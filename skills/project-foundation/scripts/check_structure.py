#!/usr/bin/env python3
"""Check the max-folders-per-level rule and regenerate INDEX.md.

Installed by project-foundation as `.claude/check-structure.py`.

Usage: python3 .claude/check-structure.py [--write]
- Exits 1 when a folder outside a git repo holds more visible subfolders than the limit.
- Nested git repos are listed, not walked: each repo keeps its own layout.
- --write regenerates INDEX.md (three levels deep).
- Settings live next to this file in `structure.json`:
  {"title": "...", "max": 7, "desc": {"folder/path": "one line"}}
  Add a line to "desc" when you add a folder.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SKIP = {"node_modules", "dist", "build", "venv", "__pycache__"}


def load():
    path = os.path.join(HERE, "structure.json")
    if not os.path.exists(path):
        return {}
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def subdirs(path):
    try:
        names = os.listdir(path)
    except (PermissionError, FileNotFoundError):
        return []
    return sorted(
        n for n in names
        if not n.startswith(".") and n not in SKIP and os.path.isdir(os.path.join(path, n))
    )


def file_count(path):
    try:
        return sum(1 for n in os.listdir(path) if not n.startswith(".") and os.path.isfile(os.path.join(path, n)))
    except (PermissionError, FileNotFoundError):
        return 0


def main():
    cfg = load()
    limit = int(cfg.get("max", 7))
    desc = cfg.get("desc", {})
    bad, lines = [], []

    def walk(rel, depth):
        path = os.path.join(ROOT, rel) if rel else ROOT
        subs = subdirs(path)
        if len(subs) > limit:
            bad.append(f"{rel or '.'}: {len(subs)} folders (max {limit})")
        for name in subs:
            child = f"{rel}/{name}" if rel else name
            full = os.path.join(ROOT, child)
            repo = os.path.exists(os.path.join(full, ".git"))
            line = f"{'  ' * depth}- **{name}/**" + (" (git repo)" if repo else "")
            if desc.get(child):
                line += f": {desc[child]}"
            files = file_count(full)
            if depth >= 1 and files:
                line += f" ({files} files)"
            lines.append(line)
            if not repo and depth < 2:
                walk(child, depth + 1)

    walk("", 0)
    if "--write" in sys.argv:
        title = cfg.get("title") or os.path.basename(ROOT)
        with open(os.path.join(ROOT, "INDEX.md"), "w", encoding="utf-8") as f:
            f.write(
                f"# {title} index\n\n"
                f"Generated by `.claude/check-structure.py --write`. Do not edit by hand.\n"
                f"Rule: max {limit} folders per level. Nested git repos are not expanded.\n\n"
                + "\n".join(lines) + "\n"
            )
    print("\n".join(bad) if bad else f"OK: every level has at most {limit} folders")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
