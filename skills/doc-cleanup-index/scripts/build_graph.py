#!/usr/bin/env python3
"""Build DIR/graph.db (SQLite) and DIR/NAVIGATION.md from DIR/tags.jsonl. Docs are never modified.

Usage: build_graph.py ROOT --index DIR
nodes(id, kind, label, path): kind = doc | project | role | subject
edges(src, dst, rel, weight): has_project | has_role | has_subject (weight = probability), links_to (md/html links
between indexed docs), shares_tags (same project and same top subject; weight = number of shared tags, capped per group).
NAVIGATION.md: project -> subject -> docs (role in brackets), low-confidence tags marked `?`.
Query example: select d.path from nodes d join edges e on e.src=d.id where e.dst='subject:backend-api/reference';
"""
import argparse, collections, json, os, re, sqlite3, posixpath as pp

ap = argparse.ArgumentParser(); ap.add_argument("root"); ap.add_argument("--index", required=True)
a = ap.parse_args(); ROOT = os.path.abspath(a.root)
docs = {}
for line in open(os.path.join(a.index, "tags.jsonl")):
    d = json.loads(line)
    if os.path.exists(os.path.join(ROOT, d["path"])):
        docs[d["path"]] = d
dbp = os.path.join(a.index, "graph.db")
if os.path.exists(dbp):
    os.remove(dbp)  # derived file, rebuilt every run
db = sqlite3.connect(dbp)
db.executescript("create table nodes(id text primary key, kind text, label text, path text, insight text);"
                 "create table edges(src text, dst text, rel text, weight real);"
                 "create index e_src on edges(src); create index e_dst on edges(dst);")
for facet, opts in json.load(open(os.path.join(a.index, "tag_pool.json"))).items():
    for t, v in opts.items():
        db.execute("insert into nodes values(?,?,?,?,?)", (f"{facet}:{t}", facet, v.get("desc", "") if isinstance(v, dict) else v, None, None))
LINK = re.compile(r"\]\(<?([^)\s#>]+)|href=[\"']([^\"'#]+)")
for p, d in docs.items():
    db.execute("insert into nodes values(?,?,?,?,?)", (f"doc:{p}", "doc", pp.basename(p), p, d.get("insight")))
    for facet, tags in d["tags"].items():
        for t, w in tags:
            db.execute("insert or ignore into nodes values(?,?,?,?,?)", (f"{facet}:{t}", facet, "", None, None))
            db.execute("insert into edges values(?,?,?,?)", (f"doc:{p}", f"{facet}:{t}", f"has_{facet}", w))
    if not p.lower().endswith(".pdf"):
        for x, y in LINK.findall(open(os.path.join(ROOT, p), errors="ignore").read(300_000)):
            t = (x or y).replace("%20", " ")
            if re.match(r"^[a-z]+:|^/", t):
                continue
            tgt = pp.normpath(pp.join(pp.dirname(p), t))
            if tgt in docs:
                db.execute("insert into edges values(?,?,?,?)", (f"doc:{p}", f"doc:{tgt}", "links_to", 1))
groups = collections.defaultdict(list)
for p, d in docs.items():
    groups[(d["tags"]["project"][0][0], d["tags"]["subject"][0][0].split("/")[0])].append(p)


def tagset(p):
    return {f"{f}:{t}" for f, ts in docs[p]["tags"].items() for t, _ in ts}


for members in groups.values():
    members = sorted(members)[:200]
    for i, x in enumerate(members):
        for y in members[i + 1:]:
            db.execute("insert into edges values(?,?,?,?)", (f"doc:{x}", f"doc:{y}", "shares_tags", len(tagset(x) & tagset(y))))
db.commit()
tree = collections.defaultdict(lambda: collections.defaultdict(list))
for p, d in docs.items():
    for proj, _ in d["tags"]["project"]:
        tree[proj][d["tags"]["subject"][0][0]].append(p)
lines = ["# Navigation: project -> subject -> documents", "",
         "Generated by `build_graph.py` from `tags.jsonl`. `?` = a tag below 0.4, check it. Relations: `graph.db`.", ""]
for proj in sorted(tree, key=lambda k: -sum(map(len, tree[k].values()))):
    lines.append(f"## {proj} ({sum(map(len, tree[proj].values()))})")
    for subj in sorted(tree[proj], key=lambda k: -len(tree[proj][k])):
        lines.append(f"### {proj} / {subj} ({len(tree[proj][subj])})")
        for p in sorted(tree[proj][subj])[:40]:
            d = docs[p]; low = min(w for ts in d["tags"].values() for _, w in ts) < 0.4
            roles = ", ".join(t for t, _ in d["tags"]["role"])
            lines.append(f"- [{p}](<{os.path.relpath(os.path.join(ROOT, p), a.index)}>) [{roles}]" + (" ?" if low else "") + (f" — {d['insight']}" if d.get("insight") else ""))
        if len(tree[proj][subj]) > 40:
            lines.append(f"- ... {len(tree[proj][subj]) - 40} more (query graph.db)")
    lines.append("")
open(os.path.join(a.index, "NAVIGATION.md"), "w").write("\n".join(lines))
print(f"{len(docs)} docs; edges: {dict(db.execute('select rel, count(*) from edges group by rel').fetchall())}")
