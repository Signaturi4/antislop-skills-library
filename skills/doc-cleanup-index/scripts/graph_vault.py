#!/usr/bin/env python3
"""Write an Obsidian / Foam graph vault from tags.jsonl so the doc graph opens inside the IDE. Docs are never modified.

Usage: graph_vault.py ROOT --index DIR [--min-docs 1] [--project NAME]
--project scopes the vault to docs tagged with that project (written to DIR/graph-NAME/) and prints the
folders to put in `foam.files.include`, so the IDE graph shows one project instead of the whole workspace.
Writes DIR/graph/: one note per tag (`project--<tag>.md`, `role--<tag>.md`, `subject--<tag>.md`) linking to every
doc that carries it (with its one-line insight), plus `_tags.md` linking all tag notes. In the graph view, tag notes
are hubs: two docs that share a tag are two hops apart, and the docs' own links show as direct edges.
View it: VS Code / Antigravity with the Foam extension (`foam.foam-vscode`, "Foam: Show Graph"), or open ROOT as an
Obsidian vault (Graph view). Re-run after every tagging run; the folder is derived and fully rewritten.
"""
import argparse, collections, json, os, shutil

ap = argparse.ArgumentParser(); ap.add_argument("root"); ap.add_argument("--index", required=True)
ap.add_argument("--min-docs", type=int, default=1); ap.add_argument("--project")
a = ap.parse_args(); ROOT = os.path.abspath(a.root); OUT = os.path.join(a.index, f"graph-{a.project}" if a.project else "graph")
pool = json.load(open(os.path.join(a.index, "tag_pool.json")))
docs = {}
for line in open(os.path.join(a.index, "tags.jsonl")):
    d = json.loads(line)
    if os.path.exists(os.path.join(ROOT, d["path"])):
        if a.project and a.project not in [t for t, _ in d["tags"]["project"]]:
            continue
        docs[d["path"]] = d
by_tag = collections.defaultdict(list)
for p, d in docs.items():
    for facet, tags in d["tags"].items():
        for t, _ in tags:
            by_tag[(facet, t)].append(p)
if os.path.isdir(OUT):
    shutil.rmtree(OUT)  # derived folder, rebuilt every run
os.makedirs(OUT)


def note(facet, tag):
    return f"{facet}--{tag.replace('/', '--')}"


hub = ["---", "type: index", "---", "# Tags", "", "Generated by `graph_vault.py`. One note per tag; open the graph view to explore.", ""]
for facet in ("project", "role", "subject"):
    hub.append(f"## {facet}")
    for (f, t), paths in sorted(by_tag.items(), key=lambda kv: -len(kv[1])):
        if f != facet or len(paths) < a.min_docs:
            continue
        v = pool.get(f, {}).get(t, {})
        desc = v.get("desc", "") if isinstance(v, dict) else v
        lines = ["---", f"type: {f}", f"title: \"{f}: {t}\"", f"docs: {len(paths)}", "---", f"# {f}: {t}", "", desc, "", f"{len(paths)} docs. Related tags: [[_tags]]", ""]
        for p in sorted(paths):
            rel = os.path.relpath(os.path.join(ROOT, p), OUT).replace(" ", "%20")
            ins = docs[p].get("insight", "")
            lines.append(f"- [{p}]({rel})" + (f" — {ins}" if ins else ""))
        open(os.path.join(OUT, note(f, t) + ".md"), "w").write("\n".join(lines) + "\n")
        hub.append(f"- [[{note(f, t)}]] ({len(paths)})")
    hub.append("")
open(os.path.join(OUT, "_tags.md"), "w").write("\n".join(hub))
if a.project:  # folders where most docs belong to the project -> foam.files.include
    tot, hit = collections.Counter(), collections.Counter()
    for line in open(os.path.join(a.index, "tags.jsonl")):
        d = json.loads(line); k = os.sep.join(d["path"].split(os.sep)[:3])
        tot[k] += 1; hit[k] += d["path"] in docs
    inc = [os.path.relpath(OUT, ROOT) + "/**/*"] + [f"{k}/**/*" for k in sorted(hit) if hit[k] >= 3 and hit[k] / tot[k] >= 0.6]
    print("foam.files.include: " + json.dumps(inc))
    print(f"outside those folders: {sum(1 for p in docs if not any(p.startswith(i[:-4]) for i in inc[1:]))} docs show as grey placeholders")
print(f"{len(by_tag)} tag notes for {len(docs)} docs -> {OUT}")
