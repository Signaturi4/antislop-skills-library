#!/usr/bin/env python3
"""Check the max-folders-per-level rule and (re)generate INDEX.md.

Usage: check_structure.py ROOT [--max 7] [--depth 3] [--desc desc.json] [--write]
- Fails (exit 1) when a folder outside a git repo has more than --max visible subfolders.
- Git repos are listed, not walked (each repo has its own layout; run the check inside it separately).
- --write writes ROOT/INDEX.md (levels 1..depth) with descriptions from --desc ({"folder/sub": "what it holds"}).
"""
import argparse, json, os, sys

ap = argparse.ArgumentParser(); ap.add_argument("root"); ap.add_argument("--max", type=int, default=7)
ap.add_argument("--depth", type=int, default=3); ap.add_argument("--desc"); ap.add_argument("--write", action="store_true")
a = ap.parse_args(); ROOT = os.path.abspath(a.root)
DESC = json.load(open(a.desc)) if a.desc else {}
bad, lines = [], []


def subdirs(p):
    try:
        return sorted(d for d in os.listdir(p) if not d.startswith(".") and os.path.isdir(os.path.join(p, d)))
    except PermissionError:
        return []


def walk(rel, depth):
    p = os.path.join(ROOT, rel)
    subs = subdirs(p)
    if len(subs) > a.max:
        bad.append(f"{rel or '.'}: {len(subs)} folders (max {a.max})")
    for s in subs:
        r = os.path.join(rel, s) if rel else s
        repo = os.path.exists(os.path.join(ROOT, r, ".git"))
        n = sum(1 for f in os.listdir(os.path.join(ROOT, r)) if not f.startswith(".") and os.path.isfile(os.path.join(ROOT, r, f)))
        lines.append(f"{'  ' * depth}- **{s}/**{' (git repo)' if repo else ''}" + (f" — {DESC[r]}" if r in DESC else "")
                     + (f" · {n} files" if n else ""))
        if not repo and depth + 1 < a.depth:
            walk(r, depth + 1)


walk("", 0)
if a.write:
    open(os.path.join(ROOT, "INDEX.md"), "w").write(
        f"# Index\n\nGenerated by `check_structure.py --write`. Rule: max {a.max} folders per level. "
        "Git repos are not expanded.\n\n" + "\n".join(lines) + "\n")
print("\n".join(bad) if bad else f"OK: every level has at most {a.max} folders")
sys.exit(1 if bad else 0)
